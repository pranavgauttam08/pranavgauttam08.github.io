// robots.txt generated from the "crawlers" policy in site.config.json.
// Deciding per purpose (not per bot) keeps the policy explainable in one sentence.

import { BOTS, PURPOSES, botsByPurpose } from './bots.mjs';

const ORDER = ['engine', 'search', 'user-fetch', 'training'];

/** Is a purpose allowed under this site's policy? Classic search engines are always allowed. */
export function isAllowed(policy = {}, purpose) {
  if (purpose === 'engine') return true;
  const flag = { search: policy.allowSearch, 'user-fetch': policy.allowUserFetch, training: policy.allowTraining }[purpose];
  return flag !== false;
}

export function renderRobots(site) {
  const lines = [
    '# Generated by scripts/build.mjs from the "crawlers" policy in site.config.json.',
    '# Edit the config, not this file. Rationale: docs/SCHEMA-SPEC.md, "Crawler policy".',
    '',
    'User-agent: *',
    'Allow: /',
    '',
  ];

  for (const purpose of ORDER) {
    const allowed = isAllowed(site.crawlers, purpose);
    lines.push(`# ${PURPOSES[purpose].title}: ${allowed ? 'allowed' : 'blocked'}`);
    for (const bot of botsByPurpose(purpose)) lines.push(`User-agent: ${bot.token}`);
    lines.push(allowed ? 'Allow: /' : 'Disallow: /', '');
  }

  lines.push(`Sitemap: ${site.siteUrl}/sitemap.xml`, '');
  return lines.join('\n');
}

export { BOTS };
